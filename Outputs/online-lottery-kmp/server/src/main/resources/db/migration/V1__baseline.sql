CREATE OR REPLACE FUNCTION validate_balanced_wallet_transaction()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    debit_total bigint;
    credit_total bigint;
    entry_count integer;
    should_validate boolean;
BEGIN
    should_validate = NEW.status = 'POSTED';
    IF TG_OP = 'UPDATE' THEN
        should_validate = should_validate AND OLD.status IS DISTINCT FROM 'POSTED';
    END IF;

    IF should_validate THEN
        SELECT
            COALESCE(SUM(amount_cents) FILTER (WHERE direction = 'DEBIT'), 0),
            COALESCE(SUM(amount_cents) FILTER (WHERE direction = 'CREDIT'), 0),
            COUNT(*)
        INTO debit_total, credit_total, entry_count
        FROM accounting_entries
        WHERE transaction_id = NEW.id;

        IF entry_count < 2 OR debit_total <> credit_total OR debit_total <> NEW.total_cents THEN
            RAISE EXCEPTION 'wallet transaction % is not balanced: debit %, credit %, total %',
                NEW.transaction_no, debit_total, credit_total, NEW.total_cents;
        END IF;

        NEW.posted_at = COALESCE(NEW.posted_at, now());
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_balanced_wallet_transaction
BEFORE INSERT OR UPDATE OF status ON wallet_transactions
FOR EACH ROW EXECUTE FUNCTION validate_balanced_wallet_transaction();

CREATE OR REPLACE FUNCTION protect_posted_accounting_entries()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_transaction_id bigint;
    transaction_status varchar(16);
BEGIN
    IF TG_OP = 'DELETE' THEN
        target_transaction_id = OLD.transaction_id;
    ELSE
        target_transaction_id = NEW.transaction_id;
    END IF;
    SELECT status INTO transaction_status FROM wallet_transactions WHERE id = target_transaction_id;
    IF transaction_status = 'POSTED' THEN
        RAISE EXCEPTION 'accounting entries for posted transaction % are immutable', target_transaction_id;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_protect_posted_accounting_entries
BEFORE INSERT OR UPDATE OR DELETE ON accounting_entries
FOR EACH ROW EXECUTE FUNCTION protect_posted_accounting_entries();
