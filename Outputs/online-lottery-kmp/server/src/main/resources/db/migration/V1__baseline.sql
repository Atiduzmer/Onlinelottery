    client_request_id       varchar(64) NOT NULL,
    provider_order_no       varchar(80),
    rejection_reason        varchar(256),
    completed_at            timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, client_request_id)
);

CREATE TABLE settlement_jobs (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_no                  varchar(40) NOT NULL UNIQUE,
    settlement_type         varchar(24) NOT NULL CHECK (settlement_type IN ('DRAW', 'MATCH', 'REFUND')),
    target_type             varchar(24) NOT NULL,
    target_id               bigint NOT NULL,
    status                  varchar(24) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'RUNNING', 'SUCCESS', 'PARTIAL_SUCCESS', 'FAILED')),
    idempotency_key         varchar(96) NOT NULL UNIQUE,
    started_at              timestamptz,
    completed_at            timestamptz,
    error_message           varchar(512),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE settlement_records (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_job_id       bigint NOT NULL REFERENCES settlement_jobs(id),
    order_id                bigint NOT NULL REFERENCES bet_orders(id),
    order_item_id           bigint REFERENCES bet_order_items(id),
    result                  varchar(16) NOT NULL CHECK (result IN ('WIN', 'LOSE', 'PUSH', 'VOID', 'REFUND')),
    stake_cents             bigint NOT NULL CHECK (stake_cents > 0),
    payout_cents            bigint NOT NULL DEFAULT 0 CHECK (payout_cents >= 0),
    calculation             jsonb NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (settlement_job_id, order_id, order_item_id)
);

CREATE TABLE prize_records (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prize_no                varchar(40) NOT NULL UNIQUE,
    user_id                 bigint NOT NULL REFERENCES users(id),
    order_id                bigint NOT NULL REFERENCES bet_orders(id),
    settlement_record_id    bigint NOT NULL REFERENCES settlement_records(id),
    gross_prize_cents       bigint NOT NULL CHECK (gross_prize_cents > 0),
    tax_cents               bigint NOT NULL DEFAULT 0 CHECK (tax_cents >= 0),
    net_prize_cents         bigint NOT NULL CHECK (net_prize_cents > 0),
    status                  varchar(24) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CREDITED', 'HELD', 'FAILED', 'REVERSED')),
