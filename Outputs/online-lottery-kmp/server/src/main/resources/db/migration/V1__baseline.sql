-- Online Lottery PostgreSQL baseline.
-- Money is stored as integer cents. Personally identifiable fields store ciphertext plus a lookup hash.

CREATE TABLE users (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_no                 varchar(32) NOT NULL UNIQUE,
    mobile_country_code     varchar(8),
    mobile_encrypted        text,
    mobile_hash             varchar(128) UNIQUE,
    nickname                varchar(64) NOT NULL,
    avatar_url              text,
    status                  varchar(24) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('PENDING', 'ACTIVE', 'FROZEN', 'CLOSED')),
    kyc_status              varchar(24) NOT NULL DEFAULT 'UNVERIFIED' CHECK (kyc_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED', 'EXPIRED')),
    risk_level              varchar(16) NOT NULL DEFAULT 'LOW' CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH', 'BLOCKED')),
    registered_at           timestamptz NOT NULL DEFAULT now(),
    last_login_at           timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    version                 bigint NOT NULL DEFAULT 0
);

CREATE TABLE user_identities (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint NOT NULL UNIQUE REFERENCES users(id),
    real_name_encrypted     text NOT NULL,
    id_type                 varchar(24) NOT NULL,
    id_number_encrypted     text NOT NULL,
    id_number_hash          varchar(128) NOT NULL UNIQUE,
    birth_date              date NOT NULL,
    status                  varchar(24) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED', 'EXPIRED')),
    verified_at             timestamptz,
    rejection_reason        varchar(256),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE user_devices (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint NOT NULL REFERENCES users(id),
    device_fingerprint_hash varchar(128) NOT NULL,
    platform                varchar(16) NOT NULL CHECK (platform IN ('ANDROID', 'IOS', 'DESKTOP', 'WEB')),
    app_version             varchar(32),
    push_token_encrypted    text,
    trusted                 boolean NOT NULL DEFAULT false,
    first_seen_at           timestamptz NOT NULL DEFAULT now(),
    last_seen_at            timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, device_fingerprint_hash)
);

CREATE TABLE auth_sessions (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint NOT NULL REFERENCES users(id),
    device_id               bigint REFERENCES user_devices(id),
    refresh_token_hash      varchar(128) NOT NULL UNIQUE,
    issued_at               timestamptz NOT NULL DEFAULT now(),
    expires_at              timestamptz NOT NULL,
    revoked_at              timestamptz,
    revoke_reason           varchar(128),
    CHECK (expires_at > issued_at)
);

CREATE TABLE user_bank_cards (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint NOT NULL REFERENCES users(id),
    bank_code               varchar(32) NOT NULL,
    card_token_encrypted    text NOT NULL,
    card_token_hash         varchar(128) NOT NULL,
    card_last4              char(4) NOT NULL,
    holder_name_encrypted   text NOT NULL,
    status                  varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED', 'EXPIRED')),
    is_default              boolean NOT NULL DEFAULT false,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, card_token_hash)
);

CREATE TABLE user_risk_profiles (
    user_id                 bigint PRIMARY KEY REFERENCES users(id),
    risk_score              integer NOT NULL DEFAULT 0 CHECK (risk_score BETWEEN 0 AND 1000),
    risk_level              varchar(16) NOT NULL DEFAULT 'LOW' CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH', 'BLOCKED')),
    flags                   jsonb NOT NULL DEFAULT '{}'::jsonb,
    last_evaluated_at       timestamptz,
    updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE lottery_games (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    varchar(32) NOT NULL UNIQUE,
    name                    varchar(64) NOT NULL,
    category                varchar(24) NOT NULL CHECK (category IN ('SPORTS', 'NUMBER')),
    sport_type              varchar(24),
    status                  varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED', 'RETIRED')),
    sales_enabled           boolean NOT NULL DEFAULT false,
    display_order           integer NOT NULL DEFAULT 0,
    config                  jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    CHECK ((category = 'SPORTS' AND sport_type IS NOT NULL) OR category = 'NUMBER')
);

CREATE TABLE lottery_play_types (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id                 bigint NOT NULL REFERENCES lottery_games(id),
    code                    varchar(48) NOT NULL,
    name                    varchar(64) NOT NULL,
    rule_version            integer NOT NULL DEFAULT 1 CHECK (rule_version > 0),
    unit_price_cents        bigint NOT NULL CHECK (unit_price_cents > 0),
    max_multiple            integer NOT NULL DEFAULT 99 CHECK (max_multiple > 0),
    status                  varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED', 'RETIRED')),
    rules                   jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (game_id, code, rule_version)
);

CREATE TABLE lottery_draws (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id                 bigint NOT NULL REFERENCES lottery_games(id),
    issue_no                varchar(32) NOT NULL,
    sale_start_at           timestamptz NOT NULL,
    sale_end_at             timestamptz NOT NULL,
    draw_at                 timestamptz NOT NULL,
    status                  varchar(24) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED', 'ON_SALE', 'SALES_CLOSED', 'DRAWING', 'PUBLISHED', 'SETTLED', 'CANCELLED')),
    sales_cents             bigint CHECK (sales_cents >= 0),
    jackpot_cents           bigint CHECK (jackpot_cents >= 0),
    result_checksum         varchar(128),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (game_id, issue_no),
    CHECK (sale_start_at < sale_end_at AND sale_end_at <= draw_at)
);

CREATE TABLE lottery_draw_numbers (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draw_id                 bigint NOT NULL REFERENCES lottery_draws(id),
    zone                    varchar(24) NOT NULL DEFAULT 'MAIN',
    position                integer NOT NULL CHECK (position > 0),
    number_value            varchar(8) NOT NULL,
    UNIQUE (draw_id, zone, position)
);

CREATE TABLE sports_competitions (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_code           varchar(64) NOT NULL UNIQUE,
    name                    varchar(96) NOT NULL,
    short_name              varchar(32),
    sport_type              varchar(24) NOT NULL,
    country_code            char(2),
    logo_url                text,
    status                  varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sports_teams (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_code           varchar(64) NOT NULL UNIQUE,
    name                    varchar(96) NOT NULL,
    short_name              varchar(32),
    sport_type              varchar(24) NOT NULL,
    country_code            char(2),
    crest_url               text,
    crest_checksum          varchar(128),
    status                  varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sports_matches (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_match_id       varchar(64) NOT NULL UNIQUE,
    competition_id          bigint NOT NULL REFERENCES sports_competitions(id),
    home_team_id            bigint NOT NULL REFERENCES sports_teams(id),
    away_team_id            bigint NOT NULL REFERENCES sports_teams(id),
    business_date           date NOT NULL,
    kickoff_at              timestamptz NOT NULL,
    sale_end_at             timestamptz,
    status                  varchar(24) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED', 'ON_SALE', 'CLOSED', 'LIVE', 'FINISHED', 'CANCELLED', 'POSTPONED')),
    home_score              integer CHECK (home_score >= 0),
    away_score              integer CHECK (away_score >= 0),
    metadata                jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    CHECK (home_team_id <> away_team_id)
);

CREATE TABLE match_markets (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id                bigint NOT NULL REFERENCES sports_matches(id),
    play_type_id            bigint NOT NULL REFERENCES lottery_play_types(id),
    market_code             varchar(48) NOT NULL,
    line_value              numeric(10, 3),
    status                  varchar(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'SUSPENDED', 'CLOSED', 'SETTLED', 'VOID')),
    version                 bigint NOT NULL DEFAULT 0,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (match_id, market_code, line_value)
);

CREATE TABLE market_selections (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id               bigint NOT NULL REFERENCES match_markets(id),
    selection_code          varchar(32) NOT NULL,
    selection_name          varchar(64) NOT NULL,
    result                  varchar(16) NOT NULL DEFAULT 'UNSET' CHECK (result IN ('UNSET', 'WIN', 'LOSE', 'PUSH', 'VOID')),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (market_id, selection_code)
);

CREATE TABLE odds_snapshots (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    selection_id            bigint NOT NULL REFERENCES market_selections(id),
    odds_decimal            numeric(12, 4) NOT NULL CHECK (odds_decimal > 1),
    status                  varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    source                  varchar(32) NOT NULL,
    valid_from              timestamptz NOT NULL,
    received_at             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE bet_orders (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no                varchar(40) NOT NULL UNIQUE,
    user_id                 bigint NOT NULL REFERENCES users(id),
    game_id                 bigint NOT NULL REFERENCES lottery_games(id),
    order_type              varchar(24) NOT NULL CHECK (order_type IN ('SPORTS_SINGLE', 'SPORTS_PARLAY', 'NUMBER_SINGLE', 'NUMBER_CHASE')),
    status                  varchar(24) NOT NULL DEFAULT 'CREATED' CHECK (status IN ('CREATED', 'PAYMENT_PENDING', 'PAID', 'TICKETING', 'TICKETED', 'PARTIAL_TICKETED', 'FAILED', 'CANCELLED', 'SETTLING', 'SETTLED', 'REFUNDED')),
    total_stake_cents       bigint NOT NULL CHECK (total_stake_cents > 0),
    potential_payout_cents  bigint CHECK (potential_payout_cents >= 0),
    currency                char(3) NOT NULL DEFAULT 'CNY',
    client_request_id       varchar(64) NOT NULL,
    submitted_at            timestamptz,
    sale_deadline_at        timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    version                 bigint NOT NULL DEFAULT 0,
    UNIQUE (user_id, client_request_id)
);

CREATE TABLE bet_order_items (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                bigint NOT NULL REFERENCES bet_orders(id),
    play_type_id            bigint NOT NULL REFERENCES lottery_play_types(id),
    draw_id                 bigint REFERENCES lottery_draws(id),
    item_no                 integer NOT NULL CHECK (item_no > 0),
    units                   integer NOT NULL CHECK (units > 0),
    multiple                integer NOT NULL DEFAULT 1 CHECK (multiple > 0),
    stake_cents             bigint NOT NULL CHECK (stake_cents > 0),
    content                 jsonb NOT NULL,
    status                  varchar(24) NOT NULL DEFAULT 'CREATED' CHECK (status IN ('CREATED', 'ACCEPTED', 'TICKETED', 'FAILED', 'CANCELLED', 'SETTLED', 'REFUNDED')),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (order_id, item_no)
);

CREATE TABLE bet_selections (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id           bigint NOT NULL REFERENCES bet_order_items(id),
    match_id                bigint REFERENCES sports_matches(id),
    market_selection_id     bigint REFERENCES market_selections(id),
    odds_snapshot_id        bigint REFERENCES odds_snapshots(id),
    selected_value          varchar(64) NOT NULL,
    accepted_odds_decimal   numeric(12, 4),
    created_at              timestamptz NOT NULL DEFAULT now(),
    CHECK ((match_id IS NULL AND market_selection_id IS NULL) OR (match_id IS NOT NULL AND market_selection_id IS NOT NULL))
);

CREATE TABLE ticket_orders (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                bigint NOT NULL REFERENCES bet_orders(id),
    ticket_order_no         varchar(40) NOT NULL UNIQUE,
    channel                 varchar(32) NOT NULL,
    status                  varchar(24) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SUBMITTED', 'SUCCESS', 'PARTIAL_SUCCESS', 'FAILED', 'CANCELLED')),
    amount_cents            bigint NOT NULL CHECK (amount_cents > 0),
    idempotency_key         varchar(80) NOT NULL UNIQUE,
    attempt_count           integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    last_error_code         varchar(64),
    last_error_message      varchar(256),
    submitted_at            timestamptz,
    completed_at            timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE official_tickets (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_order_id         bigint NOT NULL REFERENCES ticket_orders(id),
    order_item_id           bigint NOT NULL REFERENCES bet_order_items(id),
    official_ticket_no      varchar(80) NOT NULL UNIQUE,
    status                  varchar(24) NOT NULL DEFAULT 'ISSUED' CHECK (status IN ('ISSUED', 'WIN', 'LOSE', 'VOID', 'REFUNDED')),
    stake_cents             bigint NOT NULL CHECK (stake_cents > 0),
    ticket_payload          jsonb NOT NULL,
    issued_at               timestamptz NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE order_status_histories (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                bigint NOT NULL REFERENCES bet_orders(id),
    from_status             varchar(24),
    to_status               varchar(24) NOT NULL,
    reason_code             varchar(64),
    reason_message          varchar(256),
    operator_type           varchar(24) NOT NULL DEFAULT 'SYSTEM',
    operator_id             varchar(64),
    created_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE chase_plans (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chase_no                varchar(40) NOT NULL UNIQUE,
    user_id                 bigint NOT NULL REFERENCES users(id),
    game_id                 bigint NOT NULL REFERENCES lottery_games(id),
    play_type_id            bigint NOT NULL REFERENCES lottery_play_types(id),
    status                  varchar(24) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'PAUSED', 'COMPLETED', 'STOPPED', 'FAILED')),
    total_issues            integer NOT NULL CHECK (total_issues > 0),
    completed_issues        integer NOT NULL DEFAULT 0 CHECK (completed_issues >= 0),
    per_issue_stake_cents   bigint NOT NULL CHECK (per_issue_stake_cents > 0),
    total_stake_cents       bigint NOT NULL CHECK (total_stake_cents > 0),
    stop_after_win          boolean NOT NULL DEFAULT true,
    selection_content       jsonb NOT NULL,
    client_request_id       varchar(64) NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    CHECK (completed_issues <= total_issues),
    CHECK (total_stake_cents = per_issue_stake_cents * total_issues),
    UNIQUE (user_id, client_request_id)
);

CREATE TABLE chase_plan_issues (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chase_plan_id           bigint NOT NULL REFERENCES chase_plans(id),
    draw_id                 bigint NOT NULL REFERENCES lottery_draws(id),
    issue_sequence          integer NOT NULL CHECK (issue_sequence > 0),
    stake_cents             bigint NOT NULL CHECK (stake_cents > 0),
    status                  varchar(24) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ORDERED', 'TICKETED', 'SKIPPED', 'FAILED', 'REFUNDED')),
    order_id                bigint UNIQUE REFERENCES bet_orders(id),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (chase_plan_id, issue_sequence),
    UNIQUE (chase_plan_id, draw_id)
);

CREATE TABLE user_favorites (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint NOT NULL REFERENCES users(id),
    target_type             varchar(24) NOT NULL CHECK (target_type IN ('GAME', 'COMPETITION', 'TEAM', 'MATCH')),
    target_id               bigint NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, target_type, target_id)
);

CREATE TABLE wallet_accounts (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type              varchar(24) NOT NULL CHECK (owner_type IN ('USER', 'PLATFORM', 'CHANNEL')),
    owner_id                bigint NOT NULL,
    account_code            varchar(64) NOT NULL,
    account_type            varchar(32) NOT NULL CHECK (account_type IN ('AVAILABLE', 'BETTING_FROZEN', 'PRIZE', 'WITHDRAWAL_FROZEN', 'PAYMENT_PENDING', 'LOTTERY_SALES', 'PRIZE_SETTLEMENT', 'CHANNEL_CLEARING')),
    currency                char(3) NOT NULL DEFAULT 'CNY',
    status                  varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    balance_cents           bigint NOT NULL DEFAULT 0,
    version                 bigint NOT NULL DEFAULT 0,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (owner_type, owner_id, account_code)
);

CREATE TABLE wallet_transactions (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_no          varchar(48) NOT NULL UNIQUE,
    business_type           varchar(32) NOT NULL CHECK (business_type IN ('RECHARGE', 'BET_FREEZE', 'BET_CAPTURE', 'BET_UNFREEZE', 'PRIZE', 'WITHDRAW_FREEZE', 'WITHDRAW_CAPTURE', 'WITHDRAW_UNFREEZE', 'REFUND', 'ADJUSTMENT')),
    business_id             varchar(64) NOT NULL,
    idempotency_key         varchar(96) NOT NULL UNIQUE,
    status                  varchar(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'POSTED', 'REVERSED', 'FAILED')),
    total_cents             bigint NOT NULL CHECK (total_cents > 0),
    description             varchar(256),
    posted_at               timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (business_type, business_id)
);

CREATE TABLE accounting_entries (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id          bigint NOT NULL REFERENCES wallet_transactions(id),
    account_id              bigint NOT NULL REFERENCES wallet_accounts(id),
    line_no                 integer NOT NULL CHECK (line_no > 0),
    direction               varchar(8) NOT NULL CHECK (direction IN ('DEBIT', 'CREDIT')),
    amount_cents            bigint NOT NULL CHECK (amount_cents > 0),
    balance_after_cents     bigint NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (transaction_id, line_no)
);

CREATE TABLE recharge_orders (
